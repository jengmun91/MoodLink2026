// Converts src/styles/tokens.css (web, px) into src/styles/tokens.uni.css for uni-app H5 / EAP.
// Mobile design base is 375px, so 1px = 2rpx. Hairline borders (1px, 1.5px) stay in px.
// Run: npm run tokens:uniapp
import { readFileSync, writeFileSync } from 'node:fs'

const src = readFileSync(new URL('../src/styles/tokens.css', import.meta.url), 'utf8')

// Keep the mobile :root block and the language overrides; drop the desktop media query.
const withoutDesktop = src.replace(/\/\* 3 Responsive — desktop[\s\S]*?\n}\n/, '')

const KEEP_PX = /^--(border-width-thin|border-width-default|breakpoint-)/
const out = withoutDesktop
  .split('\n')
  .map((line) => {
    const m = line.match(/^(\s*)(--[\w-]+):\s*(.+);$/)
    if (!m) return line
    const [, indent, name, value] = m
    if (KEEP_PX.test(name)) return line
    const converted = value.replace(/(-?\d*\.?\d+)px/g, (_, n) => `${Math.round(Number(n) * 2 * 100) / 100}rpx`)
    return `${indent}${name}: ${converted};`
  })
  .join('\n')
  .replace(/^:root,\n\[lang\] \{/m, 'page,\n[lang] {')
  .replace(
    '/* MoodLink Design System tokens',
    '/* MoodLink Design System tokens — uni-app (rpx). GENERATED by scripts/tokens-to-uniapp.mjs; do not edit.',
  )

writeFileSync(new URL('../src/styles/tokens.uni.css', import.meta.url), out)
console.log('Wrote src/styles/tokens.uni.css')
