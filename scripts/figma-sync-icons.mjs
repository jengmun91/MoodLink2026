// Syncs the "Mental health icon library" (Figma › Variables (Design Tokens) › 6.Icons) into code:
//   1. finds every component named "Mental Health / <Style> / <Concept>" under node 6042:2638
//   2. downloads each one as SVG → src/assets/icons/mental-health/<style>/<concept>.svg
//   3. writes figma/mental-health-icons.json (node ID ↔ name ↔ style manifest)
//   4. writes one Code Connect template per icon → figma/mental-health/<style>--<concept>.figma.ts
//
// Needs a Figma personal access token with "File content: Read" (the same token used for publishing).
// Run: FIGMA_ACCESS_TOKEN=xxx npm run figma:icons      (Node 20+, uses global fetch)
import { mkdirSync, writeFileSync } from 'node:fs'

const FILE_KEY = 'Eo3tD5Lo2odmoWGf0Mfndz'
const FILE_SLUG = 'GOO001P---MoodLink-Final-For-Dev'
const ICONS_NODE = '6042:2638' // section "6.Icons"
const SOURCE =
  'https://github.com/jengmun91/MoodLink2026/blob/main/src/components/primitives/IconMentalHealth.vue'
const token = process.env.FIGMA_ACCESS_TOKEN
if (!token) throw new Error('Set FIGMA_ACCESS_TOKEN (scope: File content: Read).')

const api = async (path) => {
  const res = await fetch(`https://api.figma.com/v1/${path}`, { headers: { 'X-Figma-Token': token } })
  if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${path}`)
  return res.json()
}
const kebab = (s) =>
  s.trim().toLowerCase().replace(/&/g, 'and').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
// "Outline Color / Dark Background" → "outline-color-dark"
const styleSlug = (s) => kebab(s).replace('-dark-background', '-dark')

// 1. find components
const { nodes } = await api(`files/${FILE_KEY}/nodes?ids=${encodeURIComponent(ICONS_NODE)}`)
const icons = []
const walk = (n) => {
  if (n.type === 'COMPONENT' && /^Mental Health \//.test(n.name)) {
    const parts = n.name.split('/').map((p) => p.trim())
    const concept = parts.at(-1)
    const style = parts.slice(1, -1).join(' / ')
    icons.push({ id: n.id, figmaName: n.name, name: kebab(concept), style: styleSlug(style) })
  }
  n.children?.forEach(walk)
}
walk(nodes[ICONS_NODE].document)
if (!icons.length) throw new Error('No "Mental Health / …" components found under 6.Icons — check the node ID.')
icons.sort((a, b) => (a.style + a.name).localeCompare(b.style + b.name))

// 2. download SVGs (50 per request)
for (let i = 0; i < icons.length; i += 50) {
  const batch = icons.slice(i, i + 50)
  const { images } = await api(
    `images/${FILE_KEY}?format=svg&svg_outline_text=true&ids=${batch.map((b) => b.id).join(',')}`,
  )
  for (const icon of batch) {
    if (!images[icon.id]) {
      console.warn(`No SVG returned for ${icon.figmaName}`)
      continue
    }
    const svg = await (await fetch(images[icon.id])).text()
    const dir = new URL(`../src/assets/icons/mental-health/${icon.style}/`, import.meta.url)
    mkdirSync(dir, { recursive: true })
    writeFileSync(new URL(`${icon.name}.svg`, dir), svg)
  }
}

// 3. manifest
writeFileSync(
  new URL('../figma/mental-health-icons.json', import.meta.url),
  JSON.stringify({ fileKey: FILE_KEY, node: ICONS_NODE, synced: new Date().toISOString(), icons }, null, 2) + '\n',
)

// 4. Code Connect templates
const dir = new URL('../figma/mental-health/', import.meta.url)
mkdirSync(dir, { recursive: true })
for (const icon of icons) {
  const url = `https://www.figma.com/design/${FILE_KEY}/${FILE_SLUG}?node-id=${icon.id.replace(':', '-')}`
  writeFileSync(
    new URL(`${icon.style}--${icon.name}.figma.ts`, dir),
    `// url=${url}
// source=${SOURCE}
// component=IconMentalHealth
// GENERATED by scripts/figma-sync-icons.mjs — do not edit.
import figma from 'figma'

export default {
  example: figma.code\`<IconMentalHealth name="${icon.name}" variant="${icon.style}" />\`,
  imports: ["import { IconMentalHealth } from '@/components'"],
  id: 'mental-health--${icon.style}--${icon.name}',
  metadata: { nestable: true },
}
`,
  )
}
const styles = [...new Set(icons.map((i) => i.style))]
console.log(`Synced ${icons.length} icons in ${styles.length} styles (${styles.join(', ')}).`)
