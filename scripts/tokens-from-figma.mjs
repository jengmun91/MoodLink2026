// Generates src/styles/tokens.css from tokens/figma-variables.json (a snapshot of the
// five "MoodLink DS / …" variable collections in Figma).
// Run: npm run tokens   (also regenerates the uni-app rpx file)
//
// Output structure
//   :root, [lang]          Primitives → Semantic → Language (en/ms) → Static → Responsive (mobile)
//   @media (min-width: N)  one block per Responsive mode whose values differ from the one before it
//   :lang(zh-Hans)         Language overrides for Simplified Chinese
import { readFileSync, writeFileSync } from 'node:fs'

const snap = JSON.parse(readFileSync(new URL('../tokens/figma-variables.json', import.meta.url), 'utf8'))

const COL = {
  primitives: 'MoodLink DS / 1 Primitives',
  semantic: 'MoodLink DS / 2 Semantic',
  responsive: 'MoodLink DS / 3 Responsive',
  static: 'MoodLink DS / 4 Static',
  language: 'MoodLink DS / 5 Language',
}
const byCol = (c) => snap.vars.filter((v) => v.col === c)
const cssName = (v) => v.web?.match(/var\((--[\w-]+)\)/)?.[1] ?? '--' + v.name.replaceAll('/', '-')
const nameOf = Object.fromEntries(snap.vars.map((v) => [v.name, cssName(v)]))

// Fluid on mobile: these Responsive variables describe the design canvas, not CSS values.
const SKIP = new Set(['--viewport-width'])
const FLUID_MOBILE = { '--grid-container': '100%' }

const WEIGHT = { Regular: 400, Medium: 500, SemiBold: 600, 'Semi Bold': 600, Bold: 700 }
const unitless = (n) => /grid-columns$/.test(n)
const ms = (n) => /^--motion-(duration|delay)/.test(n)
const num = (x) => String(Math.round(x * 100) / 100)

function format(name, value) {
  if (value && typeof value === 'object' && 'alias' in value) return `var(${nameOf[value.alias]})`
  if (typeof value === 'number') {
    if (unitless(name)) return num(value)
    return num(value) + (ms(name) ? 'ms' : 'px')
  }
  if (typeof value === 'string') {
    if (/^#[0-9a-f]{6,8}$/i.test(value)) return value.toLowerCase()
    if (/weight/.test(name) && value in WEIGHT) return String(WEIGHT[value])
    if (/font-(heading|body|family-chinese)$/.test(name)) return `"${value}", sans-serif`
    return value
  }
  return String(value)
}

const line = (n, v, indent = '  ') => `${indent}${n}: ${v};`
const out = []
out.push(`/* MoodLink Design System tokens
 * GENERATED by scripts/tokens-from-figma.mjs from tokens/figma-variables.json
 * (Figma file ${snap.source.fileKey}, ${snap.source.file}, exported ${snap.source.exported}).
 * Do not edit by hand: change the Figma variable, refresh the snapshot, then run \`npm run tokens\`.
 * Mobile values apply 320–480px; desktop values from 481px (designed at 1440).
 * Language: set <html lang="en | ms | zh-Hans"> (also works on any element with a lang attribute). */
`)

// ---- :root
out.push(':root,\n[lang] {')
out.push('  /* 1 Primitives — never use directly in components */')
for (const v of byCol(COL.primitives)) out.push(line(cssName(v), format(cssName(v), v.vals.Value)))

out.push('\n  /* 2 Semantic — use these for all colours */')
for (const v of byCol(COL.semantic)) out.push(line(cssName(v), format(cssName(v), v.vals.Light)))

out.push('\n  /* 5 Language — English / Malay defaults */')
const lang = byCol(COL.language)
for (const v of lang) {
  if (JSON.stringify(v.vals.en) !== JSON.stringify(v.vals.ms))
    throw new Error(`${v.name}: en and ms differ — add a :lang(ms) block to the generator`)
  out.push(line(cssName(v), format(cssName(v), v.vals.en)))
}

out.push('\n  /* 4 Static */')
for (const v of byCol(COL.static)) out.push(line(cssName(v), format(cssName(v), v.vals.Value)))

const responsive = byCol(COL.responsive).filter((v) => !SKIP.has(cssName(v)))
const modes = snap.collections.find((c) => c.name === COL.responsive).modes.map((m) => m.name)
const base = modes[0]
out.push(`\n  /* 3 Responsive — mobile (${modes.filter((m) => +m <= 480).join(', ')}px modes) */`)
for (const v of responsive) {
  const n = cssName(v)
  out.push(line(n, FLUID_MOBILE[n] ?? format(n, v.vals[base])))
}
out.push('}')

// ---- one media block per mode that changes something (fluid variables excluded on mobile)
let prev = base
const desktopFrom = 481
for (const m of modes.slice(1)) {
  const isDesktop = +m > 480
  const changed = responsive.filter((v) => {
    const n = cssName(v)
    if (!isDesktop && n in FLUID_MOBILE) return false
    return JSON.stringify(v.vals[m]) !== JSON.stringify(v.vals[prev])
  })
  if (changed.length) {
    const min = isDesktop ? desktopFrom : +m
    out.push(`\n/* 3 Responsive — ${isDesktop ? `desktop (designed at ${m}px)` : `${m}px`} */`)
    out.push(`@media (min-width: ${min}px) {\n  :root,\n  [lang] {`)
    for (const v of changed) out.push(line(cssName(v), format(cssName(v), v.vals[m]), '    '))
    out.push('  }\n}')
  }
  prev = m
}

// ---- Chinese overrides
const zh = lang.filter((v) => JSON.stringify(v.vals['zh-Hans']) !== JSON.stringify(v.vals.en))
out.push('\n/* 5 Language — Simplified Chinese */\n:lang(zh-Hans) {')
for (const v of zh) out.push(line(cssName(v), format(cssName(v), v.vals['zh-Hans'])))
out.push('}\n')

writeFileSync(new URL('../src/styles/tokens.css', import.meta.url), out.join('\n'))
console.log(`Wrote src/styles/tokens.css (${snap.vars.length} variables, ${modes.length} responsive modes)`)
